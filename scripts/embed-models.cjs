'use strict';
// Copies every .glb the page loads (its path appears in js/*.js) into `<file>.glb.js`: the same
// model as base64 in a classic script, registered under its path. Browsers do not let a page
// opened straight from disk (file://) read the .glb, but they do load scripts;
// js/model-loader.js falls back to this copy then. Working files in assets/models (a whole
// scene export, Substance Painter exports…) are not copied. Run it after each export:
//   npm run models
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const MAX_TEXTURE = 1024;

function usedModels() {
  const found = new Set();
  for (const file of fs.readdirSync(path.join(root, 'js'))) {
    if (!file.endsWith('.js')) continue;
    const text = fs.readFileSync(path.join(root, 'js', file), 'utf8');
    for (const [, model] of text.matchAll(/'(assets\/models\/[^']+\.glb)'/g)) found.add(model);
  }
  return [...found].sort();
}

// Width × height of each texture inside a .glb (PNG and JPEG).
function textureSizes(data) {
  const jsonLength = data.readUInt32LE(12);
  const json = JSON.parse(data.toString('utf8', 20, 20 + jsonLength));
  const binary = 20 + jsonLength + 8;
  return (json.images || []).flatMap(image => {
    const view = json.bufferViews[image.bufferView];
    if (!view) return [];
    const start = binary + (view.byteOffset || 0);
    if (image.mimeType === 'image/png') return [[image.name, data.readUInt32BE(start + 16), data.readUInt32BE(start + 20)]];
    for (let at = start + 2; at < start + view.byteLength;) {
      const marker = data.readUInt16BE(at);
      if (marker >= 0xffc0 && marker <= 0xffc3) return [[image.name, data.readUInt16BE(at + 7), data.readUInt16BE(at + 5)]];
      at += 2 + data.readUInt16BE(at + 2);
    }
    return [];
  });
}

const missing = [];
for (const key of usedModels()) {
  const source = path.join(root, key);
  if (!fs.existsSync(source)) { missing.push(key); continue; }
  const data = fs.readFileSync(source);
  if (data.toString('ascii', 0, 4) !== 'glTF') throw new Error(`${key} is not a .glb file`);
  fs.writeFileSync(`${source}.js`, `// Generated by scripts/embed-models.cjs from ${path.basename(source)} (${data.length} bytes). Do not edit.
(window.TimeExperience = window.TimeExperience || {}).embeddedModels = Object.assign(window.TimeExperience.embeddedModels || {}, {
  ${JSON.stringify(key)}: '${data.toString('base64')}'
});
`);
  console.log(`${key}.js (${Math.round(fs.statSync(`${source}.js`).size / 1024)} KB)`);
  const large = textureSizes(data).filter(([, width, height]) => Math.max(width, height) > MAX_TEXTURE);
  if (large.length) console.log(`  ⚠ texturas de más de ${MAX_TEXTURE} px (pesadas para la web): ${large.map(([name, w, h]) => `${name} ${w}×${h}`).join(', ')}`);
}
if (missing.length) console.log(`Sin archivo todavía (se usa el objeto provisional): ${missing.join(', ')}`);
